"""COMPARISON OPERATORS"""

a = 10
b = 20

print(a == b)  #False
print(a != b)  #True
print(a > b)   #False
print(a < b)   #True
print(a >= b)  #False
print(a <= b)  #True
print(a is b)  #False
print(a is not b)  #True

print(ord('a'))  #97
print(ord('A'))  #65
print(ord('z'))  #122 #ORD means a unique code of a particular character in the ASCII table 
print(ord('Z'))  #90