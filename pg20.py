#datatype


"""Datatype - 1
   NUMBERS
   
   integer
   float
   Complex"""
a = 34

print(type(a))  #integer

b = 34.5

print(type(b))  #float

c = 12/3

print(type(c))  #float

d = 34j

print(type(d)) #complex

"""Datatype - 2
   STRING """

st = 'My name is shivam'

print(type(st))  #string

"""Datatype - 3
   BOOLEAN """

x = True
print(type(x))  #boolean
y = False
print(type(y))  #boolean